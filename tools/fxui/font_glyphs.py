"""Glifi del font pixel "CAR Pixel" (regolare e grassetto), disegnati a mano.

Convenzioni:
- ogni glifo è (top, righe): 'top' è l'altezza sopra la linea di base della prima riga;
  la riga che poggia sulla linea di base ha altezza 1, quelle del discendente 0 e -1;
- '#' = pixel pieno, '.' = vuoto; tutte le righe di un glifo hanno la stessa larghezza;
- maiuscole e cifre alte 7 px, minuscole con occhio di 5 px, discendenti di 2 px,
  accenti delle maiuscole alle altezze 9-10 (con una riga libera), delle minuscole a 7-8;
- avanzamento = larghezza + 1 px, salvo dove indicato (spazio, ecc.).
Il grassetto si ottiene "spalmando" ogni glifo di 1 px a destra (aste verticali di 2 px);
i glifi che così si impasterebbero (M, N, W, m, w, #, Q, 0, punteggiatura) sono ridisegnati.
"""
from __future__ import annotations

ASCENT = 10   # px sopra la linea di base (accenti delle maiuscole compresi)
DESCENT = 2   # px sotto la linea di base
CAP = 7
XH = 5


def _parse(art: str) -> list[str]:
    rows = [r.strip() for r in art.strip("\n").split("\n")]
    rows = [r for r in rows if r != ""]
    w = len(rows[0])
    assert all(len(r) == w for r in rows), rows
    return rows


def _table(spec: dict) -> dict:
    out = {}
    for ch, (top, art) in spec.items():
        out[ch] = (top, _parse(art) if isinstance(art, str) else art)
    return out


