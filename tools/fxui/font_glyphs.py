def charset(table: dict) -> list[str]:
    return sorted(table.keys(), key=ord)


def check(table: dict, name: str) -> None:
    """Controlli di coerenza: altezze entro ascendente/discendente, righe uguali."""
    for ch, (top, rows) in table.items():
        w = len(rows[0])
        assert all(len(r) == w for r in rows), (name, ch)
        bottom = top - len(rows) + 1
        assert top <= ASCENT, (name, ch, top)
        assert bottom >= 1 - DESCENT, (name, ch, bottom)
    for ch in "àèéìòùÀÈÉÌÒÙ0123456789":
        assert ch in table, (name, ch)
