def _smear(rows: list[str]) -> list[str]:
    out = []
    for r in rows:
        w = len(r)
        line = []
        for c in range(w + 1):
            a = c < w and r[c] == "#"
            b = c - 1 >= 0 and r[c - 1] == "#"
            line.append("#" if (a or b) else ".")
        out.append("".join(line))
    return out


