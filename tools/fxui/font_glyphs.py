def _compose(table: dict, bold: bool) -> None:
    for ch, (base, kind, col) in _COMPOSE.items():
        top, rows = table[base]
        w = len(rows[0])
        if bold:
            acc = _GRAVE_B if kind == "grave" else _ACUTE_B
        else:
            acc = _GRAVE if kind == "grave" else _ACUTE
        aw = len(acc[0])
        c0 = col
        if c0 + aw > w:
            c0 = w - aw
        # riga dell'accento: 1 riga libera sopra il glifo
        acc_rows = []
        for r in acc:
            line = ["."] * w
            for i, v in enumerate(r):
                if v == "#":
                    line[c0 + i] = "#"
            acc_rows.append("".join(line))
        new_top = top + 3
        table[ch] = (new_top, acc_rows + ["." * w] + list(rows))


